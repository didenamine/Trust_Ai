"""File storage behind a small interface (US03).

Code that needs a stored file (CV import, US05 analysis, US24 ATS) goes through
`FileStorage`, never through the filesystem directly, so the local `uploads/`
folder can later be swapped for another backend (S3, Azure Blob...) without
touching the callers.
"""

import os
from pathlib import Path
from typing import Protocol

from app.core.config import get_settings


class FileStorage(Protocol):
    def save(self, key: str, content: bytes) -> None: ...

    def read(self, key: str) -> bytes: ...

    def delete(self, key: str) -> None:
        """Remove the file. Does nothing if it does not exist."""
        ...


class LocalFileStorage:
    """Stores files under a local root folder, e.g. `uploads/<user_id>/<uuid>.pdf`."""

    def __init__(self, root: Path) -> None:
        self.root = root.resolve()

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        # Keys are generated by the app, but never let one escape the root folder.
        if not path.is_relative_to(self.root):
            raise ValueError(f"Invalid storage key: {key!r}")
        return path

    def save(self, key: str, content: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a temporary file first so a crash never leaves a half-written CV.
        tmp_path = path.with_name(f".{path.name}.tmp")
        tmp_path.write_bytes(content)
        os.replace(tmp_path, path)

    def read(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


def get_storage() -> FileStorage:
    """FastAPI dependency (overridden in tests with a temporary folder)."""
    return LocalFileStorage(get_settings().upload_dir)
